"""
Evaluation metrics for BioForm-LM.

Metrics for assessing model performance on BioFormBench:
- Top-k recipe recall: does generated recipe match known-good ones?
- Calibration: predicted stability vs actual stability
- Diversity: variety of generated recipes (not all identical)
"""

import numpy as np
from typing import List, Tuple, Dict, Optional
from scipy.stats import spearmanr, kendalltau
import logging

logger = logging.getLogger(__name__)


class RecallMetric:
    """
    Top-k recipe recall metric.

    Given:
    - Known-good formulations for a protein (from BioFormBench)
    - Generated formulations from the model

    Measure: what fraction of generated formulations are "close" to known-good ones?

    "Close" is defined as Euclidean distance in formulation parameter space:
    - Normalized pH, IS, osmolarity, temperature
    - Fuzzy match on buffer species and stabilizers (0.5 penalty if not exact)
    """

    def __init__(self, distance_threshold: float = 0.15):
        """
        Initialize RecallMetric.

        Args:
            distance_threshold: Euclidean distance threshold for "match" (default: 0.15)
        """
        self.distance_threshold = distance_threshold

    def _formulation_to_vector(self, formulation: Dict) -> np.ndarray:
        """
        Convert formulation dict to normalized vector for distance computation.

        Normalizes continuous parameters to [0, 1], encodes buffer/stabilizer categorically.

        Args:
            formulation: Dict with pH, IS, osmolarity, temperature, etc.

        Returns:
            numpy array of normalized parameters
        """
        # Normalize continuous parameters (ranges from typical biologics formulations)
        ph = np.clip(formulation.get("ph", 7.0), 2, 12)
        ph_norm = (ph - 2) / 10

        is_mm = np.clip(formulation.get("ionic_strength_mm", 150), 1, 1000)
        is_norm = (np.log(is_mm) - np.log(1)) / (np.log(1000) - np.log(1))

        osmol = np.clip(formulation.get("osmolarity_mosm_kg", 300), 50, 500)
        osmol_norm = (osmol - 50) / 450

        temp = np.clip(formulation.get("temperature_c", 25), -20, 50)
        temp_norm = (temp + 20) / 70

        # Combine normalized parameters
        vector = np.array([ph_norm, is_norm, osmol_norm, temp_norm])

        return vector

    def _formulation_distance(
        self, form1: Dict, form2: Dict, include_categorical: bool = True
    ) -> float:
        """
        Compute distance between two formulations.

        Args:
            form1: First formulation dict
            form2: Second formulation dict
            include_categorical: If True, add penalty for buffer/stabilizer mismatch

        Returns:
            Distance in [0, 1]
        """
        # Euclidean distance on continuous parameters
        vec1 = self._formulation_to_vector(form1)
        vec2 = self._formulation_to_vector(form2)

        continuous_dist = np.linalg.norm(vec1 - vec2)

        # Penalty for buffer species mismatch
        categorical_penalty = 0.0
        if include_categorical:
            buffer1 = form1.get("buffer_species", "").lower()
            buffer2 = form2.get("buffer_species", "").lower()
            if buffer1 != buffer2:
                categorical_penalty += 0.15

            # Penalty for stabilizer set mismatch
            stabs1 = set(form1.get("stabilizers_json", "{}").split("|")) if isinstance(
                form1.get("stabilizers_json"), str
            ) else set()
            stabs2 = set(form2.get("stabilizers_json", "{}").split("|")) if isinstance(
                form2.get("stabilizers_json"), str
            ) else set()

            if stabs1 != stabs2:
                # Penalize based on Jaccard distance of stabilizers
                if len(stabs1) + len(stabs2) > 0:
                    jaccard = 1.0 - (
                        len(stabs1 & stabs2) / len(stabs1 | stabs2)
                    )
                    categorical_penalty += 0.1 * jaccard

        return continuous_dist + categorical_penalty

    def compute(
        self,
        generated_formulations: List[Dict],
        known_good_formulations: List[Dict],
        k: int = 5,
    ) -> Tuple[float, int]:
        """
        Compute top-k recall.

        Args:
            generated_formulations: List of formulations generated by model
            known_good_formulations: List of known-good (real) formulations
            k: Number of top candidates to consider

        Returns:
            (recall_score, num_matches) where recall_score is in [0, 1]
        """
        if len(known_good_formulations) == 0:
            return 1.0, len(generated_formulations)

        # Take top-k generated formulations
        top_k_generated = generated_formulations[:k]

        # For each known-good, find closest generated
        matches = 0
        for known_good in known_good_formulations:
            min_dist = float("inf")
            for generated in top_k_generated:
                dist = self._formulation_distance(known_good, generated)
                min_dist = min(min_dist, dist)

            if min_dist <= self.distance_threshold:
                matches += 1

        recall = matches / len(known_good_formulations)

        return recall, matches


class CalibrationMetric:
    """
    Calibration metric: predicted vs actual stability.

    Measure: how well do model's predicted stability scores match real outcomes?

    Uses Spearman and Kendall rank correlations (robust to scaling issues).
    """

    def __init__(self):
        """Initialize CalibrationMetric."""
        pass

    def compute(
        self,
        predicted_scores: List[float],
        actual_scores: List[float],
    ) -> Dict[str, float]:
        """
        Compute calibration metrics.

        Args:
            predicted_scores: Model's predicted stability scores [0, 1]
            actual_scores: Real measured stability scores [0, 1]

        Returns:
            Dict with keys:
            - spearman_r: Spearman rank correlation
            - spearman_p: p-value
            - kendall_tau: Kendall rank correlation
            - kendall_p: p-value
            - mae: Mean absolute error
            - rmse: Root mean squared error
        """
        predicted = np.array(predicted_scores)
        actual = np.array(actual_scores)

        if len(predicted) < 2:
            return {
                "spearman_r": np.nan,
                "spearman_p": np.nan,
                "kendall_tau": np.nan,
                "kendall_p": np.nan,
                "mae": np.nan,
                "rmse": np.nan,
            }

        # Rank correlations
        spearman_r, spearman_p = spearmanr(predicted, actual)
        kendall_tau, kendall_p = kendalltau(predicted, actual)

        # Error metrics
        mae = np.mean(np.abs(predicted - actual))
        rmse = np.sqrt(np.mean((predicted - actual) ** 2))

        return {
            "spearman_r": spearman_r,
            "spearman_p": spearman_p,
            "kendall_tau": kendall_tau,
            "kendall_p": kendall_p,
            "mae": mae,
            "rmse": rmse,
        }


class DiversityMetric:
    """
    Diversity metric: variety of generated recipes.

    Measure: do generated formulations span the formulation space,
    or are they all clustered in one region?

    Uses average pairwise distance in normalized formulation space.
    """

    def __init__(self):
        """Initialize DiversityMetric."""
        self.recall_metric = RecallMetric()  # Reuse distance function

    def compute(self, generated_formulations: List[Dict]) -> Dict[str, float]:
        """
        Compute diversity metrics.

        Args:
            generated_formulations: List of generated formulations

        Returns:
            Dict with keys:
            - mean_pairwise_distance: Average distance between pairs
            - std_pairwise_distance: Std dev of pairwise distances
            - coverage: Fraction of parameter space covered (proxy metric)
        """
        if len(generated_formulations) < 2:
            return {
                "mean_pairwise_distance": 0.0,
                "std_pairwise_distance": 0.0,
                "coverage": 0.0,
            }

        # Compute all pairwise distances
        distances = []
        for i, form1 in enumerate(generated_formulations):
            for j, form2 in enumerate(generated_formulations):
                if i < j:
                    dist = self.recall_metric._formulation_distance(form1, form2)
                    distances.append(dist)

        distances = np.array(distances)

        # Coverage: fraction of parameter space spanned
        # (proxy: max pairwise distance / theoretical max)
        theoretical_max_distance = 2.0  # Rough upper bound
        coverage = (np.max(distances) if len(distances) > 0 else 0.0) / theoretical_max_distance

        return {
            "mean_pairwise_distance": float(np.mean(distances)) if len(distances) > 0 else 0.0,
            "std_pairwise_distance": float(np.std(distances)) if len(distances) > 0 else 0.0,
            "coverage": min(1.0, coverage),  # Clip to [0, 1]
        }
